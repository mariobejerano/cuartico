-- 3. One subcategory under Alimentos per distinct remaining text (case-insensitive); its name is MIN of the group
INSERT INTO categories (parent_id, name, name_en, name_key, product_type, depth, active, version,
                        created_at, updated_at, created_by, updated_by)
SELECT (SELECT r.id FROM categories r WHERE r.parent_id IS NULL AND r.product_type = 'FOOD'),
       MIN(TRIM(p.category)), NULL, LOWER(TRIM(p.category)), 'FOOD', 2, TRUE, 0,
       CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 'system', 'system'
FROM products p
WHERE p.category IS NOT NULL
  AND TRIM(p.category) <> ''
  AND LOWER(TRIM(p.category)) NOT IN (SELECT a.alias_key FROM category_alias_tmp a)
GROUP BY LOWER(TRIM(p.category));

-- 4. Products: category_id (alias -> root; other text -> its subcategory; no text -> Alimentos)
ALTER TABLE products ADD COLUMN category_id BIGINT;

UPDATE products
SET category_id = (SELECT c.id
                   FROM categories c
                   WHERE c.parent_id IS NULL
                     AND c.product_type = (SELECT a.product_type
                                           FROM category_alias_tmp a
                                           WHERE a.alias_key = LOWER(TRIM(products.category))))
WHERE category IS NOT NULL
  AND TRIM(category) <> ''
  AND LOWER(TRIM(category)) IN (SELECT alias_key FROM category_alias_tmp);

UPDATE products
SET category_id = (SELECT c.id
                   FROM categories c
                   WHERE c.parent_id = (SELECT r.id FROM categories r WHERE r.parent_id IS NULL AND r.product_type = 'FOOD')
                     AND c.name_key = LOWER(TRIM(products.category)))
WHERE category_id IS NULL
  AND category IS NOT NULL
  AND TRIM(category) <> '';

UPDATE products
SET category_id = (SELECT r.id FROM categories r WHERE r.parent_id IS NULL AND r.product_type = 'FOOD')
WHERE category_id IS NULL;

ALTER TABLE products ALTER COLUMN category_id SET NOT NULL;
ALTER TABLE products ADD CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id);
CREATE INDEX idx_products_category ON products (category_id);

