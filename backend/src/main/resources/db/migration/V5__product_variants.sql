-- HU-16 / ADR-003 (decision 3): product variants. The variant is what is bought, stored and sold: it owns the SKU,
-- the low-stock threshold and the stock cache (variant_stock replaces product_stock, ADR-002 addendum).
-- Every existing product gets exactly one hidden variant (no size, no color) with its old SKU, threshold and stock.
-- color_key = LOWER(TRIM(color)) is computed by the DATABASE in one place (the application writes it with the same
-- function via @ColumnTransformer), like categories.name_key in V4.

CREATE TABLE product_variants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT        NOT NULL REFERENCES products (id),
    sku        VARCHAR(50),
    size       VARCHAR(20),
    color      VARCHAR(30),
    color_key  VARCHAR(30),
    min_stock  NUMERIC(12,3) NOT NULL DEFAULT 0,
    active     BOOLEAN       NOT NULL DEFAULT TRUE,
    version    BIGINT        NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(50),
    updated_by VARCHAR(50),
    CONSTRAINT uk_product_variants_sku UNIQUE (sku),
    CONSTRAINT uk_product_variants_options UNIQUE NULLS NOT DISTINCT (product_id, size, color_key),
    CONSTRAINT ck_product_variants_min_stock CHECK (min_stock >= 0)
);
CREATE INDEX idx_product_variants_product ON product_variants (product_id);

CREATE TABLE variant_stock (
    variant_id    BIGINT        PRIMARY KEY REFERENCES product_variants (id),
    on_hand       NUMERIC(14,3) NOT NULL DEFAULT 0,
    reserved      NUMERIC(14,3) NOT NULL DEFAULT 0,
    average_cost  NUMERIC(14,4),
    cost_currency VARCHAR(3),
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_variant_stock_non_negative CHECK (on_hand >= 0 AND reserved >= 0)
);

ALTER TABLE products ADD COLUMN has_variants BOOLEAN NOT NULL DEFAULT FALSE;

-- 1. One variant per product (active: the activation of the product rules; size and color stay NULL)
INSERT INTO product_variants (product_id, sku, min_stock, active, version, created_at, updated_at, created_by, updated_by)
SELECT p.id, p.sku, p.min_stock, TRUE, 0, p.created_at, p.updated_at, p.created_by, p.updated_by
FROM products p;

-- 2. One stock row per variant, with the values of the old product_stock (a missing row would become zeros,
--    so the invariant "each variant has exactly one stock row" always holds)
INSERT INTO variant_stock (variant_id, on_hand, reserved, average_cost, cost_currency, updated_at)
SELECT v.id, COALESCE(s.on_hand, 0), COALESCE(s.reserved, 0), s.average_cost, s.cost_currency,
       COALESCE(s.updated_at, v.updated_at)
FROM product_variants v
LEFT JOIN product_stock s ON s.product_id = v.product_id;

-- 3. Drop the old structures (constraints first, explicitly, because H2 does not drop them with the column)
DROP TABLE product_stock;
ALTER TABLE products DROP CONSTRAINT uk_products_sku;
ALTER TABLE products DROP CONSTRAINT ck_products_min_stock;
ALTER TABLE products DROP COLUMN sku;
ALTER TABLE products DROP COLUMN min_stock;
